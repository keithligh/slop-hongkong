#!/usr/bin/env node
// Project the Central OSM pedestrian extract into js/hk-pedestrian-data.js.
//
//   node tools/build-hk-pedestrian.mjs tools/data/hk/osm_pedestrian.json
//
// The query is tools/data/q_hk_pedestrian.overpassql (Central core).
// tools/fetch-hk.sh writes the gitignored JSON. This script writes the module the page imports.

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { hkCoreProject } from '../js/city-config.js';
import { collectHkPedestrian } from '../js/hk-pedestrian.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const input = path.resolve(process.argv[2] || path.join(root, 'tools/data/hk/osm_pedestrian.json'));
const output = path.join(root, 'js/hk-pedestrian-data.js');

const raw = JSON.parse(readFileSync(input, 'utf8'));
const elements = Array.isArray(raw.elements) ? raw.elements : [];
const features = collectHkPedestrian(elements, (lon, lat) => hkCoreProject(lon, lat));
const payload = {
  fetched: '2026-10-24',
  bbox: [22.276, 114.150, 22.288, 114.170],
  attribution: '© OpenStreetMap contributors',
  ...features
};
const body = `// Generated by tools/build-hk-pedestrian.mjs. Do not edit.
// Central core OSM pavement, crossings, bus stops, benches, and street lamps.
// Source query: tools/data/q_hk_pedestrian.overpassql
// ${payload.attribution}. Fetched ${payload.fetched}.
export const HK_PEDESTRIAN = ${JSON.stringify(payload)};
`;
writeFileSync(output, body);
const walks = payload.walks.length;
const stops = payload.stops.length;
console.log(
  `[pedestrian] walks ${walks} areas ${payload.areas.length} crossings ${payload.crossings.length} ` +
  `stops ${stops} furniture ${payload.furniture.length} → ${output}`
);
